#!/usr/bin/env python3
"""Fail-closed preflight for a nightly execution slice.

Slice launch (--slice) checks only what is needed to *start Helix*
(GitHub auth/org, repos after r0-a, previous HITL). Azure and HCP are
**per-task**: a missing RAFFA_AZURE_SUBSCRIPTION_ID must not stop a
GitHub-only or file-only task. Those tasks run; the task that actually
calls az / terraform apply / HCP emits HALTED via --task.

Usage (cwd = .helix):
  python scripts/check_slice_prereqs.py --slice r0-a
  python scripts/check_slice_prereqs.py --from-current
  python scripts/check_slice_prereqs.py --task reports/workitems/.../task-01.md
  python scripts/check_slice_prereqs.py --check azure_subscription
  python scripts/check_slice_prereqs.py --record-hitl r0-a
"""

