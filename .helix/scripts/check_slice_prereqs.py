def _load_slice_table() -> dict[str, dict]:
    """HITL chain from cut_nightly_slices.py MANIFEST (JSON subset written as YAML)."""
    if not MANIFEST.is_file():
        raise SystemExit(
            "missing reports/plan/slices/MANIFEST.yaml — run "
            "python scripts/cut_nightly_slices.py"
        )
    data = json.loads(MANIFEST.read_text(encoding="utf-8"))
    table: dict[str, dict] = {}
    for row in data["slices"]:
        table[row["id"]] = {
            "title": row["title"],
            "previous": row["previous"],
            "checks": list(row["checks"]),
        }
    return table


