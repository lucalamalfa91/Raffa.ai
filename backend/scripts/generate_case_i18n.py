#!/usr/bin/env python3
"""Generates the Italian catalogues of the AskRaffa 4.0 engines from their C# sources.

Every user-facing message in Raffa.Renewals/Application/Cases and Raffa.Savings/Application/Verifiable
is built with ``B("English id {x}", "Italian {x}", ...)`` (the prototype's ``B(en,it)`` / ``S(en,it)``
pairs). The English template is the message id; this script collects the pairs and writes

  web/src/i18n/it/case4.ts   (IT_CASE4)
  web/src/i18n/it/quote4.ts  (IT_QUOTE4)

It fails when one id has two different Italian texts (give one of them a context note: "Term⟦condition⟧")
or when the two sides use different placeholders.

Usage (from the repository root):  python3 backend/scripts/generate_case_i18n.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
TARGETS = [
    (ROOT / "backend/src/Raffa.Renewals/Application/Cases", ROOT / "web/src/i18n/it/case4.ts", "IT_CASE4",
     "Italian for the AskRaffa 4.0 renewal case engine (backend Raffa.Renewals/Application/Cases)."),
    (ROOT / "backend/src/Raffa.Savings/Application/Verifiable", ROOT / "web/src/i18n/it/quote4.ts", "IT_QUOTE4",
     "Italian for the AskRaffa 4.0 quote check and savings report (backend Raffa.Savings/Application/Verifiable)."),
]

STR = r'"((?:[^"\\]|\\.)*)"'
CALL = re.compile(r'\bB\(\s*' + STR + r'\s*,\s*' + STR, re.S)
NEUTRAL = re.compile(r'\bN\(\s*' + STR, re.S)
PH = re.compile(r'\{(\w+)\}')


def unescape(s: str) -> str:
    return s.encode("utf-8").decode("unicode_escape").encode("latin-1").decode("utf-8") if "\\" in s else s


def ts_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def collect(src: pathlib.Path):
    pairs, errors = {}, []
    for f in sorted(src.rglob("*.cs")):
        text = f.read_text(encoding="utf-8")
        for m in CALL.finditer(text):
            en, it = unescape(m.group(1)), unescape(m.group(2))
            if set(PH.findall(it)) - set(PH.findall(en)):
                errors.append(f"{f.name}: placeholders differ: {en!r} / {it!r}")
            if en in pairs and pairs[en] != it:
                errors.append(f"{f.name}: two Italian texts for {en!r}: {pairs[en]!r} / {it!r}")
            pairs.setdefault(en, it)
        for m in NEUTRAL.finditer(text):
            en = unescape(m.group(1))
            pairs.setdefault(en, en)
    return pairs, errors


def main() -> int:
    failed = False
    for src, out, name, doc in TARGETS:
        pairs, errors = collect(src)
        for e in errors:
            print("ERROR", e, file=sys.stderr)
        failed |= bool(errors)
        lines = [
            "/**",
            f" * {doc}",
            " * GENERATED by backend/scripts/generate_case_i18n.py from the engine's B(en, it) pairs — do not edit by hand.",
            " * Keys are the English message ids (the engine's CaseText `id`); values may use the same {placeholders}.",
            " */",
            "",
            f"export const {name}: Readonly<Record<string, string>> = {{",
        ]
        for en in sorted(pairs):
            lines.append(f"  {ts_string(en)}: {ts_string(pairs[en])},")
        lines += ["};", ""]
        out.write_text("\n".join(lines), encoding="utf-8")
        print(f"{out.relative_to(ROOT)}: {len(pairs)} messages")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
